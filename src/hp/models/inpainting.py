"""Pose completion with the whole reverse process of RSGM: inpainting on SO(3)^J (and the same for DPoser in its
Euclidean space, dposer_inpaint, at the end of the module).

The hidden joints are generated by the time reversal of RSGM from t = 1 (uniform rotations) down to eps, the sampler of
RSGM.sample() (geodesic Euler-Maruyama); the visible joints are kept consistent with the observation y at every step.
The pull of the hidden joints toward a plausible pose so happens at all noise levels, the large ones included, where
the score is trained on implausible poses, and not only at the small noise of score distillation.

The forward process of RSGM noises every joint independently (x_t = x_0 exp(IGSO(3) of Brownian time s(t))), so
q(x_t^visible | y) is exact: the observed rotations noised by IGSO(3) of time s(t). Per step t -> t_next:

    replacement:  x^visible <- y exp(IGSO(3) noise of s(t))  (a fresh draw), then a reverse step of all joints
                  (RePaint's known part; Lugmayr et al. 2022)
    resampling:   `resample` = r > 1 repeats the step r times, with the pose at t_next noised back to t in between
                  (x <- x exp(IGSO(3) noise of s(t) - s(t_next)), the forward Brownian motion), so that the hidden
                  joints adapt to the visible ones (RePaint with jump length 1)
    guidance:     the reverse step is moved by -guidance * grad / sqrt(loss) of the loss sum over the visible joints of
                  d(x0_hat, y)^2, x0_hat = x_t exp(s(t) score(x_t, t)) the one-step denoising (Tweedie on SO(3)),
                  the gradient taken through the network in the tangent coordinates of x_t (DPS, Chung et al. 2023,
                  with their normalization by the norm of the residual)

A model with per-joint noise (RSGM.joint_scale) has the Brownian time s_j(t) of every joint instead of s(t): the noise of
the replacement and of the resampling, the one-step denoising and the drift and diffusion of the reverse step (beta_j)
are then those of each joint; the isotropic model is unchanged.

At the end the visible joints are replaced by the observation. Replacement and guidance can be used alone or
together; with neither, the result is an unconditional sample of the prior with the observed joints pasted in.
"""
from typing import Optional

import roma
import torch

from hp.models import igso3
from hp.models.rsgm import RSGM, exp_frame


def _igso3_noise(model: RSGM, s: float, shape) -> torch.Tensor:
    """Tangent coordinates [*shape, 3] of IGSO(3) noise of one Brownian time s, drawn on the model's device in its
    dtype (the GPU does not wait for the CPU). s is clamped to the range of the model's angle table (the ends are far
    below and above any step that matters). model.noise_on_cpu: drawn on the CPU in float64 and copied (the old way)."""
    s = min(max(float(s), model.angles.s_min), model.angles.s_max)
    device, dtype = model.device, model.dtype
    if model.noise_on_cpu:
        noise = model.angles.sample_at(s, shape)[..., None] * igso3.random_axes(tuple(shape))
        return noise.to(device, dtype)
    angles = model.angles.sample_at(s, shape, device, dtype)
    return angles[..., None] * igso3.random_axes(tuple(shape), device=device, dtype=dtype)


def _joint_noise(model: RSGM, s: torch.Tensor, n: int) -> torch.Tensor:
    """Tangent coordinates [n, J', 3] of IGSO(3) noise with the Brownian time s[j] (float64 [J']) of every joint, the
    same for the n poses: as _igso3_noise, for a model with per-joint noise."""
    s = s.clamp(model.angles.s_min, model.angles.s_max)
    device, dtype = model.device, model.dtype
    shape = (n, len(s))
    if model.noise_on_cpu or device.type == "mps":  # mps: no float64 for the range check of the table
        noise = model.angles.sample(s.expand(*shape))[..., None] * igso3.random_axes(shape)
        return noise.to(device, dtype)
    angles = model.angles.sample(s.to(device).expand(*shape), dtype=dtype)
    return angles[..., None] * igso3.random_axes(shape, device=device, dtype=dtype)


def _noise(model: RSGM, s, joints: torch.Tensor, n: int) -> torch.Tensor:
    """IGSO(3) noise [n, J', 3] of the joints `joints` (bool [J]) for the Brownian time s: a number (isotropic model)
    or the per-joint times [J] (float64)."""
    if model.joint_scale is None:
        return _igso3_noise(model, s, (n, int(joints.sum())))
    return _joint_noise(model, s[joints.cpu()], n)


def _guidance(model: RSGM, x: torch.Tensor, t: torch.Tensor, y: torch.Tensor, vis: torch.Tensor):
    """The score at x and the normalized gradient (tangent coordinates in the frame of x, [B, J, 3]) of the squared
    geodesic error of the visible joints of the one-step denoising x0_hat, through the network."""
    delta = torch.zeros(*x.shape[:2], 3, device=x.device, dtype=x.dtype, requires_grad=True)
    with torch.enable_grad():
        xx = exp_frame(x, delta)
        score = model.score(xx, t)
        x0_hat = exp_frame(xx, model.joint_s(t)[..., None] * score)
        loss = roma.rotmat_to_rotvec(x0_hat[:, vis].transpose(-1, -2) @ y[:, vis]).pow(2).sum((-1, -2))  # [B]
        (grad,) = torch.autograd.grad(loss.sum(), delta)
    return score.detach(), grad / loss.detach().sqrt().clamp_min(1e-12)[:, None, None]


@torch.no_grad()
def rsgm_inpaint(model: RSGM, observed: torch.Tensor, visible: torch.Tensor, steps: int = 200,
                 schedule: str = "uniform", resample: int = 1, guidance: float = 0.0, replace: bool = True,
                 init: Optional[torch.Tensor] = None) -> torch.Tensor:
    """Poses [B, J, 3, 3] that keep the visible joints (bool [J]) of `observed` [B, J, 3, 3] and fill the others by
    the reverse process of RSGM (see the module doc). steps: reverse steps from t = 1 to eps, on the grid `schedule`
    ("uniform" or "edm", RSGM.sample_times); resample: r of RePaint; guidance: the step size of the DPS term (0: none);
    replace: the replacement of the visible joints; init: the start at t = 1 (default: uniform rotations).
    Network calls: steps * resample (with a backward pass each when guidance > 0)."""
    if resample < 1 or steps < 1:
        raise ValueError(f"steps and resample must be >= 1, got {steps}, {resample}.")
    if not replace and guidance <= 0:
        raise ValueError("use replace=True, guidance > 0 or both: with neither the observation is not used.")
    device, dtype = model.device, model.dtype
    n, joints = observed.shape[:2]
    y = observed.to(device, dtype)
    vis = visible.to(device)
    seen = vis[None, :, None, None]
    if init is None:
        x = roma.random_rotmat(n * joints, device=device, dtype=dtype).reshape(n, joints, 3, 3)
    else:
        x = init.to(device, dtype).reshape(n, joints, 3, 3)
    times = model.sample_times(steps, schedule)
    n_vis = int(vis.sum())
    for i in range(steps):
        t64, t_next64 = times[i], times[i + 1]
        t = t64.to(device, dtype).expand(n)
        dt = (t64 - t_next64).to(device, dtype)
        if model.joint_scale is None:
            beta, s_t, s_next = model.beta(t64).to(device, dtype), model.s(t64), model.s(t_next64)
        else:  # per joint: beta_j [J, 1] and the Brownian times s_j [J] (float64, CPU)
            beta = model.joint_beta(t64.reshape(1))[0].to(device, dtype)[:, None]
            s_t, s_next = model.joint_s(t64.reshape(1))[0], model.joint_s(t_next64.reshape(1))[0]
        everyone = torch.ones(joints, dtype=torch.bool)
        for r in range(resample):
            if replace and n_vis:
                x[:, vis] = exp_frame(y[:, vis], _noise(model, s_t, vis.cpu(), n))
            if guidance > 0:
                score, grad = _guidance(model, x, t, y, vis)
            else:
                score = model.score(x, t)
            step = beta * score * dt + torch.sqrt(beta * dt) * torch.randn(n, joints, 3, device=device, dtype=dtype)
            if guidance > 0:
                step = step - guidance * grad
            x = exp_frame(x, step)
            if r < resample - 1:  # back from t_next to t by the forward Brownian motion
                x = exp_frame(x, _noise(model, s_t - s_next, everyone, n))
    return torch.where(seen, y, x)


# ---- the same for DPoser: the reverse sub-VP SDE in its z-scored axis-angle space ----

def dposer_times(model, steps: int, schedule: str = "uniform", rho: float = 7.0) -> torch.Tensor:
    """steps + 1 times from 1 down to model.sample_eps (float64). "uniform": evenly spaced; "edm": evenly spaced in
    sigma^(1/rho), sigma = std / alpha the noise-to-signal ratio of the sub-VP SDE (dense at small t, as the EDM grid
    of RSGM.sample_times), the times found by bisection (sigma grows with t)."""
    eps = model.sample_eps
    if schedule == "uniform":
        return torch.linspace(1.0, eps, steps + 1, dtype=torch.float64)
    if schedule != "edm":
        raise ValueError(f"schedule must be 'uniform' or 'edm', got {schedule!r}.")

    def sigma(t):
        alpha, std = model.marginal(t)
        return std / alpha

    ends = sigma(torch.tensor([1.0, eps], dtype=torch.float64)) ** (1 / rho)
    target = (ends[0] + torch.linspace(0, 1, steps + 1, dtype=torch.float64) * (ends[1] - ends[0])) ** rho
    low, high = torch.full_like(target, eps), torch.ones_like(target)
    for _ in range(100):
        mid = (low + high) / 2
        above = sigma(mid) > target
        high, low = torch.where(above, mid, high), torch.where(above, low, mid)
    times = (low + high) / 2
    times[0], times[-1] = 1.0, eps
    return times


def _dposer_renoise(model, x: torch.Tensor, t, t_next) -> torch.Tensor:
    """x [B, 3J] at time t_next noised forward to t > t_next by the exact transition of the sub-VP SDE: mean
    (alpha(t) / alpha(t_next)) x and variance std(t)^2 - (alpha(t) / alpha(t_next))^2 std(t_next)^2 (a linear
    SDE)."""
    alpha, std = model.marginal(torch.as_tensor(t, dtype=torch.float64))
    alpha_next, std_next = model.marginal(torch.as_tensor(t_next, dtype=torch.float64))
    a = alpha / alpha_next
    var = (std ** 2 - a ** 2 * std_next ** 2).clamp_min(0)
    return a.to(x) * x + var.sqrt().to(x) * torch.randn_like(x)


def _dposer_guidance(model, x: torch.Tensor, t: torch.Tensor, y: torch.Tensor, vis: torch.Tensor):
    """The score of DPoser at x [B, 3J] and the normalized gradient [B, 3J] (in its normalized coordinates) of the
    squared geodesic error of the visible joints of the one-step denoising x0_hat = (x - std eps_hat) / alpha
    (Tweedie), through the network."""
    alpha, std = model.marginal(t)
    with torch.enable_grad():
        xx = x.detach().requires_grad_(True)
        noise = model.noise_prediction(xx, t)
        x0_hat = model.denormalize((xx - std[:, None] * noise) / alpha[:, None])  # [B, J, 3, 3]
        loss = roma.rotmat_to_rotvec(x0_hat[:, vis].transpose(-1, -2) @ y[:, vis]).pow(2).sum((-1, -2))  # [B]
        (grad,) = torch.autograd.grad(loss.sum(), xx)
    grad = torch.nan_to_num(grad)
    return -noise.detach() / std[:, None], grad / loss.detach().sqrt().clamp_min(1e-12)[:, None]


@torch.no_grad()
def dposer_inpaint(model, observed: torch.Tensor, visible: torch.Tensor, steps: int = 200, schedule: str = "uniform",
                   resample: int = 1, guidance: float = 0.0, replace: bool = True,
                   init: Optional[torch.Tensor] = None) -> torch.Tensor:
    """rsgm_inpaint for DPoser (hp.models.dposer): poses [B, J, 3, 3] that keep the visible joints (bool [J]) of
    `observed` and fill the others by the reverse sub-VP SDE (Euler-Maruyama, as DPoser.sample) from N(0, I) at t = 1
    down to sample_eps, in the z-scored axis-angle space of the model. Per step t -> t_next:

        replacement:  the visible coordinates <- alpha(t) y + std(t) z, the exact q(x_t | y) of the forward process,
                      which noises every coordinate independently
        resampling:   r > 1 repeats the step, with x at t_next noised back to t by the exact forward transition
                      x <- (alpha(t) / alpha(t_next)) x + sqrt(std(t)^2 - (alpha(t) / alpha(t_next))^2 std(t_next)^2) z
        guidance:     -guidance * grad / sqrt(loss) of the squared geodesic error of the visible joints of the one-step
                      denoising (Tweedie), the gradient in the normalized coordinates (DPS)

    The last step returns its mean (DPoser's noise removal); the visible joints are then replaced by the observation.
    The options are those of rsgm_inpaint (the guidance has another scale: the coordinates are z-scored axis-angle)."""
    if resample < 1 or steps < 1:
        raise ValueError(f"steps and resample must be >= 1, got {steps}, {resample}.")
    if not replace and guidance <= 0:
        raise ValueError("use replace=True, guidance > 0 or both: with neither the observation is not used.")
    if not getattr(model, "isotropic_noise", True):
        raise NotImplementedError("dposer_inpaint assumes N(0, I) noise; this DPoser has a noise_scale.")
    device, dtype = model.device, model.dtype
    n, joints = observed.shape[:2]
    y = observed.to(device, dtype)
    vis = visible.to(device)
    coords = vis.repeat_interleave(3)
    y_norm = model.normalize(y)
    if init is None:
        x = torch.randn(n, 3 * joints, device=device, dtype=dtype)
    else:
        x = init.to(device, dtype).reshape(n, -1)
    x_mean = x
    times = dposer_times(model, steps, schedule)
    n_vis = int(coords.sum())
    for i in range(steps):
        t64, t_next64 = times[i], times[i + 1]
        alpha, std = (v.to(device, dtype) for v in model.marginal(t64))
        t = t64.to(device, dtype).expand(n)
        h = (t64 - t_next64).to(device, dtype)
        g = model.diffusion(t64).to(device, dtype)
        beta = model.beta(t64).to(device, dtype)
        for r in range(resample):
            if replace and n_vis:
                x[:, coords] = alpha * y_norm[:, coords] + std * torch.randn(n, n_vis, device=device, dtype=dtype)
            if guidance > 0:
                score, grad = _dposer_guidance(model, x, t, y, vis)
            else:
                score = model.score(x, t)
            x_mean = x + (0.5 * beta * x + g ** 2 * score) * h
            if guidance > 0:
                x_mean = x_mean - guidance * grad
            x = x_mean + g * torch.sqrt(h) * torch.randn_like(x)
            if r < resample - 1:  # back from t_next to t by the forward transition
                x = _dposer_renoise(model, x, t64, t_next64)
    return torch.where(vis[None, :, None, None], y, model.denormalize(x_mean))
