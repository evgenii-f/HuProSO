"""Pose completion with the whole reverse process of RSGM: inpainting on SO(3)^J.

The hidden joints are generated by the time reversal of RSGM from t = 1 (uniform rotations) down to eps, the sampler of
RSGM.sample() (geodesic Euler-Maruyama); the visible joints are kept consistent with the observation y at every step.
The pull of the hidden joints toward a plausible pose so happens at all noise levels, the large ones included, where
the score is trained on implausible poses, and not only at the small noise of score distillation.

The forward process of RSGM noises every joint independently (x_t = x_0 exp(IGSO(3) of Brownian time s(t))), so
q(x_t^visible | y) is exact: the observed rotations noised by IGSO(3) of time s(t). Per step t -> t_next:

    replacement:  x^visible <- y exp(IGSO(3) noise of s(t))  (a fresh draw), then a reverse step of all joints
                  (RePaint's known part; Lugmayr et al. 2022)
    resampling:   `resample` = r > 1 repeats the step r times, with the pose at t_next noised back to t in between
                  (x <- x exp(IGSO(3) noise of s(t) - s(t_next)), the forward Brownian motion), so that the hidden
                  joints adapt to the visible ones (RePaint with jump length 1)
    guidance:     the reverse step is moved by -guidance * grad / sqrt(loss) of the loss sum over the visible joints of
                  d(x0_hat, y)^2, x0_hat = x_t exp(s(t) score(x_t, t)) the one-step denoising (Tweedie on SO(3)),
                  the gradient taken through the network in the tangent coordinates of x_t (DPS, Chung et al. 2023,
                  with their normalization by the norm of the residual)

At the end the visible joints are replaced by the observation. Replacement and guidance can be used alone or
together; with neither, the result is an unconditional sample of the prior with the observed joints pasted in.
"""
from typing import Optional

import roma
import torch

from hp.models import igso3
from hp.models.rsgm import RSGM, exp_frame


def _igso3_noise(model: RSGM, s: torch.Tensor, shape) -> torch.Tensor:
    """Tangent coordinates [*shape, 3] of IGSO(3) noise of Brownian time s (broadcast to shape), on the CPU in float64.
    s is clamped to the range of the model's angle table (the ends are far below and above any step that matters)."""
    s = torch.as_tensor(s, dtype=torch.float64).expand(*shape)
    s = s.clamp(model.angles.s_min, model.angles.s_max)
    return model.angles.sample(s)[..., None] * igso3.random_axes(tuple(shape))


def _guidance(model: RSGM, x: torch.Tensor, t: torch.Tensor, y: torch.Tensor, vis: torch.Tensor):
    """The score at x and the normalized gradient (tangent coordinates in the frame of x, [B, J, 3]) of the squared
    geodesic error of the visible joints of the one-step denoising x0_hat, through the network."""
    delta = torch.zeros(*x.shape[:2], 3, device=x.device, dtype=x.dtype, requires_grad=True)
    with torch.enable_grad():
        xx = exp_frame(x, delta)
        score = model.score(xx, t)
        x0_hat = exp_frame(xx, model.s(t)[:, None, None] * score)
        loss = roma.rotmat_to_rotvec(x0_hat[:, vis].transpose(-1, -2) @ y[:, vis]).pow(2).sum((-1, -2))  # [B]
        (grad,) = torch.autograd.grad(loss.sum(), delta)
    return score.detach(), grad / loss.detach().sqrt().clamp_min(1e-12)[:, None, None]


@torch.no_grad()
def rsgm_inpaint(model: RSGM, observed: torch.Tensor, visible: torch.Tensor, steps: int = 200,
                 schedule: str = "uniform", resample: int = 1, guidance: float = 0.0, replace: bool = True,
                 init: Optional[torch.Tensor] = None) -> torch.Tensor:
    """Poses [B, J, 3, 3] that keep the visible joints (bool [J]) of `observed` [B, J, 3, 3] and fill the others by
    the reverse process of RSGM (see the module doc). steps: reverse steps from t = 1 to eps, on the grid `schedule`
    ("uniform" or "edm", RSGM.sample_times); resample: r of RePaint; guidance: the step size of the DPS term (0: none);
    replace: the replacement of the visible joints; init: the start at t = 1 (default: uniform rotations).
    Network calls: steps * resample (with a backward pass each when guidance > 0)."""
    if resample < 1 or steps < 1:
        raise ValueError(f"steps and resample must be >= 1, got {steps}, {resample}.")
    if not replace and guidance <= 0:
        raise ValueError("use replace=True, guidance > 0 or both: with neither the observation is not used.")
    device, dtype = model.device, model.dtype
    n, joints = observed.shape[:2]
    y = observed.to(device, dtype)
    vis = visible.to(device)
    seen = vis[None, :, None, None]
    if init is None:
        x = roma.random_rotmat(n * joints, device=device, dtype=dtype).reshape(n, joints, 3, 3)
    else:
        x = init.to(device, dtype).reshape(n, joints, 3, 3)
    times = model.sample_times(steps, schedule)
    n_vis = int(vis.sum())
    for i in range(steps):
        t64, t_next64 = times[i], times[i + 1]
        t = t64.to(device, dtype).expand(n)
        dt = (t64 - t_next64).to(device, dtype)
        beta = model.beta(t64).to(device, dtype)
        for r in range(resample):
            if replace and n_vis:
                noise = _igso3_noise(model, model.s(t64), (n, n_vis)).to(device, dtype)
                x[:, vis] = exp_frame(y[:, vis], noise)
            if guidance > 0:
                score, grad = _guidance(model, x, t, y, vis)
            else:
                score = model.score(x, t)
            step = beta * score * dt + torch.sqrt(beta * dt) * torch.randn(n, joints, 3, device=device, dtype=dtype)
            if guidance > 0:
                step = step - guidance * grad
            x = exp_frame(x, step)
            if r < resample - 1:  # back from t_next to t by the forward Brownian motion
                back = _igso3_noise(model, model.s(t64) - model.s(t_next64), (n, joints)).to(device, dtype)
                x = exp_frame(x, back)
    return torch.where(seen, y, x)
